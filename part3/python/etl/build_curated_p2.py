def nhanes():
    """Merge the requested 2021–2023 NHANES component files by SEQN."""
    demo = pd.read_sas(RAW / "nhanes" / "DEMO_L.xpt", format="xport", encoding="utf-8")
    diq = pd.read_sas(RAW / "nhanes" / "DIQ_L.xpt", format="xport", encoding="utf-8")
    bmx = pd.read_sas(RAW / "nhanes" / "BMX_L.xpt", format="xport", encoding="utf-8")
    demo_cols = ["SEQN", "RIAGENDR", "RIDAGEYR", "RIDRETH3", "WTMEC2YR", "SDMVSTRA", "SDMVPSU"]
    diq_cols = ["SEQN", "DIQ010", "DID040", "DIQ160", "DIQ180", "DIQ050", "DID060", "DIQ060U", "DIQ070"]
    bmx_cols = ["SEQN", "BMXBMI", "BMXWT", "BMXHT", "BMXWAIST"]
    result = demo[demo_cols].merge(diq[diq_cols], how="left", on="SEQN").merge(bmx[bmx_cols], how="left", on="SEQN")
    result.to_csv(CURATED / "nhanes_2021_2023_diabetes_body_measures.csv", index=False)
    print(f"NHANES rows={len(result):,}; columns={len(result.columns)}")


def brfss():
    """Create a deterministic 50,000-row reservoir sample of the requested fields."""
    archive = RAW / "brfss" / "LLCP2024XPT.zip"
    extract_path = Path("/private/tmp/LLCP2024.XPT")
    if not extract_path.exists():
        with zipfile.ZipFile(archive) as zf, zf.open("LLCP2024.XPT ") as source, extract_path.open("wb") as target:
            while block := source.read(16 * 1024 * 1024):
                target.write(block)
    wanted = ["DIABETE4", "_SMOKER3", "EXERANY2", "_TOTINDA", "_BMI5", "_BMI5CAT", "_AGEG5YR", "_SEX"]
    randomizer = random.Random(20260722)
    reservoir = []
    seen = 0
    for chunk in pd.read_sas(extract_path, format="xport", encoding="utf-8", chunksize=10000):
        records = chunk[wanted].to_dict("records")
        for record in records:
            seen += 1
            if len(reservoir) < 50000:
                reservoir.append(record)
            else:
                spot = randomizer.randrange(seen)
                if spot < 50000:
                    reservoir[spot] = record
    pd.DataFrame(reservoir, columns=wanted).to_csv(CURATED / "brfss_2024_life_risk_sample_50000.csv", index=False)
    print(f"BRFSS rows processed={seen:,}; curated reservoir rows={len(reservoir):,}")


